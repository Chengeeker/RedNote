"""Port the retained optical equations to Android's live RenderNode shader input."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1] / 'app/src/main/assets/glass'

def clean(text):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    text = re.sub(r'//[^\n]*', '', text)
    text = re.sub(r'#ifdef LGR_GLES_FLIP_SAMPLE_Y.*?#endif', '', text, flags=re.S)
    text = re.sub(r'#if DEBUG_GEOMETRY.*?#endif', '', text, flags=re.S)
    return text

original = clean((root / 'liquid_glass_render.frag').read_text(encoding='utf-8'))
render = original[original.index('const vec3 LUMA_WEIGHTS'):].replace('uniform float uLayerFade;', '')
render = render[:render.index('uniform sampler2D')] + '''
uniform shader background;
vec4 sampleBackground(vec2 uv) {
    return background.eval(clamp(uv * uSize, vec2(0.5), uSize - 0.5));
}
''' + render[render.index('vec4 textureBilinear'):]
render = render.replace('void main() {', 'vec4 main(vec2 fragCoord) {')
render = render.replace('vec2 fragCoord = FlutterFragCoord().xy;', '')
render = re.sub(r'vec4 geometryData = texture\(uGeometryTexture,.*?;',
                'vec4 geometryData = floor(geometry(fragCoord) * 255.0 + 0.5) / 255.0;', render)
render = re.sub(r'fragColor = vec4\(0\);\s*return;', 'return vec4(0);', render)
render = re.sub(r'fragColor\s*=\s*vec4\(finalColor.rgb \* alpha, alpha\)(?: \* \(1\.0 - uLayerFade\))?;',
                'return vec4(finalColor.rgb * alpha, alpha);', render)
# These surfaces never enable the library's interleaved frost-row material.
render = render[:render.index('vec3 texelAt')] + render[render.index('vec4 main'):]
render = re.sub(r'if \(uFrost.x > 0.0\) \{.*?\n    \}', '', render, flags=re.S)

geo = clean((root / 'liquid_glass_geometry_blended.frag').read_text(encoding='utf-8'))
primitive = geo[geo.index('float sdfRRect('):geo.index('float sdfRRectAsym(')]
encode = geo[geo.index('vec4 encodeGeometryData('):geo.index('layout(location = 0) out')]
geometry = geo[geo.index('void main() {'):]
geometry = geometry.replace('void main() {', 'vec4 geometry(vec2 fragCoord) {')
geometry = geometry.replace('vec2 fragCoord = FlutterFragCoord().xy;', '')
geometry = geometry.replace('float uBlend = uOpticalProps.w;', '')
geometry = geometry.replace('float uNumShapes = uShapeSettings.x;', '')
geometry = geometry.replace('float uDpr = uShapeSettings.y;', 'float uDpr = uEdgeConfig.z * 3.0;')
geometry = geometry.replace(', int(uNumShapes), uBlend', '')
geometry = re.sub(r'fragColor\s*=\s*(.*?);\s*return;', r'return \1;', geometry, flags=re.S)
geometry = geometry.replace('fragColor = encodeGeometryData(normal.xy, height, uThickness, foregroundAlpha);',
                            'return encodeGeometryData(normal.xy, height, uThickness, foregroundAlpha);')
uniform_end = render.index('uniform shader background;')
render = render[:uniform_end] + '''
uniform float uNativeEdge;
uniform vec4 shape;
''' + primitive + '''
float sceneSDF(vec2 p) { return sdfRRect(p - shape.xy, shape.zw * 0.5, 9999.0); }
''' + encode + geometry + render[uniform_end:]
render = re.sub(r'\n\s*\n', '\n', render)
assert 'fragColor' not in render and 'texture(' not in render and 'frostAt(' not in render
header = '''// Copyright 2025 Tim Lehmann; Copyright 2026 Sebastian Degenaar.
// SPDX-License-Identifier: MIT. Derived from the retained liquid_glass_widgets shaders.
// Generated by tool/generate_glass_agsl.py; same optics, live Canvas input, one capsule.
'''
(root / 'liquid_glass.agsl').write_text(header + render, encoding='utf-8')
print('Generated live glass shader')
